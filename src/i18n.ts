export type LanguageMode = 'system' | 'zh-CN' | 'en'
export type AppLanguage = Exclude<LanguageMode, 'system'>

export function resolveLanguage(mode: LanguageMode, systemLanguages: readonly string[]): AppLanguage {
  if (mode !== 'system') return mode
  return systemLanguages.some((language) => language.toLowerCase().startsWith('zh')) ? 'zh-CN' : 'en'
}

